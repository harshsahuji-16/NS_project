"""One-Time Pad (Vernam Cipher) implementation using Modular Alphabet Arithmetic.

The One-Time Pad is mathematically unbreakable (Information-Theoretic Security)
ONLY when four strict criteria are satisfied:
1. The key is truly uniformly random (generated by high-entropy source).
2. The key is at least as long as the plaintext.
3. The key is kept completely secret.
4. The key is NEVER reused for any other message.

If a key is reused or generated by a predictable PRNG, security collapses completely.
"""

import secrets
import string

OTP_SECURITY_WARNING = (
    "SECURITY WARNING: A One-Time Pad is only information-theoretically secure if "
    "the key is uniformly random, kept strictly secret, at least as long as the message, "
    "and NEVER reused. Reusing a key across two messages ('two-time pad') leaks "
    "plaintext statistics and allows cryptanalysis."
)


def generate_otp_key(length: int) -> str:
    """Generate a cryptographically secure random alphabetic key of given length.
    Uses Python's secrets module (cryptographically strong PRNG).
    """
    if length <= 0:
        return ""
    return "".join(secrets.choice(string.ascii_uppercase) for _ in range(length))


def validate_otp_key(key: str, required_length: int) -> tuple[bool, str]:
    """Validate OTP key against required alphabetic length."""
    if not isinstance(key, str):
        return False, "Key must be a string."

    clean_key = [c for c in key if c.isalpha()]
    if len(clean_key) < required_length:
        return (
            False,
            f"Key is too short! Message requires {required_length} alphabetic characters, "
            f"but key only contains {len(clean_key)} letters.",
        )
    return True, ""


def encrypt_otp(plaintext: str, key: str) -> tuple[str, str]:
    """Encrypt plaintext using One-Time Pad modular alphabet arithmetic.

    Formula: C_i = (P_i + K_i) mod 26
    Preserves case and non-alphabetic characters.

    Returns:
        (ciphertext, key_used)
    """
    alpha_count = sum(1 for c in plaintext if c.isalpha())
    is_valid, err_msg = validate_otp_key(key, alpha_count)
    if not is_valid:
        raise ValueError(f"Invalid OTP key: {err_msg}")

    clean_key = [c.upper() for c in key if c.isalpha()]
    key_idx = 0
    result = []

    for char in plaintext:
        if char.isalpha():
            shift = ord(clean_key[key_idx]) - ord('A')
            base = ord('A') if char.isupper() else ord('a')
            enc_char = chr((ord(char) - base + shift) % 26 + base)
            result.append(enc_char)
            key_idx += 1
        else:
            result.append(char)

    key_used = "".join(clean_key[:alpha_count])
    return "".join(result), key_used


def decrypt_otp(ciphertext: str, key: str) -> str:
    """Decrypt ciphertext using One-Time Pad modular alphabet arithmetic.

    Formula: P_i = (C_i - K_i + 26) mod 26
    Preserves case and non-alphabetic characters.
    """
    alpha_count = sum(1 for c in ciphertext if c.isalpha())
    is_valid, err_msg = validate_otp_key(key, alpha_count)
    if not is_valid:
        raise ValueError(f"Invalid OTP key: {err_msg}")

    clean_key = [c.upper() for c in key if c.isalpha()]
    key_idx = 0
    result = []

    for char in ciphertext:
        if char.isalpha():
            shift = ord(clean_key[key_idx]) - ord('A')
            base = ord('A') if char.isupper() else ord('a')
            dec_char = chr((ord(char) - base - shift + 26) % 26 + base)
            result.append(dec_char)
            key_idx += 1
        else:
            result.append(char)

    return "".join(result)
